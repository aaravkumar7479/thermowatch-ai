export const api = {
  hotspots: async () => {
    if (!base) return { data: mockHotspots, mode: "Demo Mode" };
    try {
      const res = await fetch(`${base}/hotspots`);
      if (!res.ok) throw Error();
      const json = await res.json();
      const data = (json.data || json).map((x) => ({
        ...x,
        category: x.category || x.predicted_category,
        latitude: Number(x.latitude || x.lat),
        longitude: Number(x.longitude || x.lng),
        risk: Number(x.risk || x.risk_score),
      }));
      return { data, mode: "Backend Connected" };
    } catch {
      return { data: mockHotspots, mode: "Demo Mode" };
    }
  },
};
